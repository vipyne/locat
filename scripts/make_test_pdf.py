"""Regenerate tests/fixtures/one_page.pdf, a minimal single-page PDF built by hand
(catalog, pages, page, content stream, font, xref) so the fixture stays reproducible
byte-for-byte."""

from pathlib import Path

TEXT = "Hello from the hand-written locat PDF fixture. It mentions an axolotl."


def build_pdf(text: str) -> bytes:
    stream = f"BT /F1 12 Tf 72 720 Td ({text}) Tj ET".encode()
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length %d >>\nstream\n" % len(stream) + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]
    out = bytearray(b"%PDF-1.4\n")
    offsets = []
    for number, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += b"%d 0 obj\n" % number + body + b"\nendobj\n"
    xref_at = len(out)
    out += b"xref\n0 %d\n" % (len(objects) + 1)
    out += b"0000000000 65535 f \n"
    for offset in offsets:
        out += b"%010d 00000 n \n" % offset
    out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (
        len(objects) + 1,
        xref_at,
    )
    return bytes(out)


def main() -> None:
    path = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "one_page.pdf"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(build_pdf(TEXT))
    print(path)


if __name__ == "__main__":
    main()
